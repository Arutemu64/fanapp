// Writes src/lib/api/generated/responseSchemaHashes.gen.ts: for every operation
// with a JSON success body, a short hash of that body's shape. The persisted
// query cache stamps each saved query with its operation's hash and drops the
// ones whose hash changed (queryPersister.ts), so a deploy discards only the
// saved responses whose shape it changed — not the whole cache, and not the
// queued writes stored beside it. Run after openapi-ts (`pnpm generate-api`),
// which empties the output folder first.
//
// The hash covers what decides whether a saved body still fits the types:
// properties, types, required, enums, formats, unions and nested $refs (inlined,
// so a change deep inside a referenced schema counts). Documentation keys are
// dropped, so rewording a field's description busts nothing.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const SPEC_PATH = '../shared/openapi/openapi.json';
const OUTPUT_PATH = 'src/lib/api/generated/responseSchemaHashes.gen.ts';
const REF_PREFIX = '#/components/schemas/';
const DOCUMENTATION_KEYS = new Set(['description', 'title', 'example', 'examples', 'default']);

type Json = null | boolean | number | string | Json[] | { [key: string]: Json };

interface Spec {
	paths: Record<string, Record<string, { operationId?: string; responses?: Record<string, Json> }>>;
	components?: { schemas?: Record<string, Json> };
}

const spec = JSON.parse(readFileSync(SPEC_PATH, 'utf8')) as Spec;
const schemas = spec.components?.schemas ?? {};

// Inlines $refs and drops documentation keys. A schema already being inlined
// further up (a recursive type) stays a bare $ref, which is still part of the
// shape by name.
function shapeOf(node: Json, inlining: Set<string> = new Set()): Json {
	if (Array.isArray(node)) {
		return node.map((item) => shapeOf(item, inlining));
	}
	if (node === null || typeof node !== 'object') {
		return node;
	}

	const ref = node.$ref;
	if (typeof ref === 'string' && ref.startsWith(REF_PREFIX)) {
		const name = ref.slice(REF_PREFIX.length);
		const target = schemas[name];
		if (inlining.has(name) || target === undefined) {
			return { $ref: name };
		}
		return shapeOf(target, new Set([...inlining, name]));
	}

	const shape: Record<string, Json> = {};
	for (const key of Object.keys(node).sort()) {
		if (DOCUMENTATION_KEYS.has(key)) continue;
		shape[key] = shapeOf(node[key] as Json, inlining);
	}
	return shape;
}

function jsonSuccessBodies(responses: Record<string, Json>): Json[] {
	const bodies: Json[] = [];
	for (const status of Object.keys(responses).sort()) {
		if (!status.startsWith('2')) continue;
		const response = responses[status] as { content?: Record<string, { schema?: Json }> };
		const schema = response.content?.['application/json']?.schema;
		if (schema !== undefined) bodies.push(schema);
	}
	return bodies;
}

// hey-api's query keys carry the operation id camel-cased (`get_schedule` →
// `_id: 'getSchedule'`), which is what the persister looks the hash up by.
function camelCase(operationId: string): string {
	return operationId.replace(/[_-]+([a-z0-9])/g, (_match, letter: string) => letter.toUpperCase());
}

const hashes: Record<string, string> = {};
for (const operations of Object.values(spec.paths)) {
	for (const operation of Object.values(operations)) {
		if (!operation.operationId) continue;
		const bodies = jsonSuccessBodies(operation.responses ?? {});
		if (bodies.length === 0) continue;
		const canonical = JSON.stringify(bodies.map((body) => shapeOf(body)));
		hashes[camelCase(operation.operationId)] = createHash('sha256')
			.update(canonical)
			.digest('hex')
			.slice(0, 16);
	}
}

const entries = Object.keys(hashes)
	.sort()
	.map((id) => `\t${id}: '${hashes[id]}'`)
	.join(',\n');

writeFileSync(
	OUTPUT_PATH,
	`// This file is auto-generated by scripts/responseSchemaHashes.ts from the OpenAPI spec.

/** Operation id → hash of its JSON success body's shape. */
export const responseSchemaHashes: Readonly<Record<string, string>> = {
${entries}
};
`
);
