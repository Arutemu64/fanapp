from typing import Protocol

from fanfan.application.dto.schedule import ScheduleEntryDTO, ScheduleEventFullDTO
from fanfan.core.models.schedule_entry import ScheduleEntry
from fanfan.core.vo.schedule_entry import ScheduleEntryId


class ScheduleEntryGateway(Protocol):
    async def lock_for_edit(self) -> None:
        """Serialize schedule edits until the current transaction ends.

        Row locks alone cannot: two edits that read the same pair of neighbours
        both compute the same ``order`` between them, since a locking read only
        re-checks the rows it already found, never the row that just moved into
        the gap. Call it first, before any read the edit depends on.
        """
        ...

    async def add(self, entry: ScheduleEntry) -> None: ...
    async def get_by_id(self, entry_id: ScheduleEntryId) -> ScheduleEntry | None: ...
    async def get_first(self) -> ScheduleEntry | None: ...
    async def get_current(self) -> ScheduleEntry | None: ...
    async def get_next(self) -> ScheduleEntry | None:
        """The first non-skipped event after the current one; never a block start."""
        ...

    async def list_all(self) -> list[ScheduleEntry]: ...
    async def get_next_by_order(self, order: float) -> ScheduleEntry | None: ...
    async def get_previous_by_order(self, order: float) -> ScheduleEntry | None: ...
    async def save(self, entry: ScheduleEntry) -> None: ...
    async def delete(self, entry: ScheduleEntry) -> None: ...

    async def read_next_event(self) -> ScheduleEventFullDTO | None: ...

    async def read_current_event(self) -> ScheduleEventFullDTO | None: ...

    async def read_list_schedule(self) -> list[ScheduleEntryDTO]: ...
